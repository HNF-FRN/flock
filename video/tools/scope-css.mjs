// Copies Flock's own renderer CSS into the film, scoped so the island and the
// settings window can live in one page:
//   - every selector is prefixed with the scope class (html/body/:root become the scope root)
//   - :hover / :active / :focus-visible also get class twins (.fx-hover, .fx-active, .fx-focus)
//     so the film can show those states without a real pointer
//   - @keyframes are renamed per scope (both files define `pulse`)
// Run: node video/tools/scope-css.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FLOCK = path.resolve(HERE, '../../src/renderer');
const OUT = path.resolve(HERE, '../film/vendor');

/** Splits CSS into top-level blocks: { prelude, body } (body without braces) or { text } for statements. */
function blocks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    // skip whitespace and comments
    const ws = /^(\s+|\/\*[\s\S]*?\*\/)/.exec(css.slice(i));
    if (ws) { i += ws[0].length; continue; }
    const open = css.indexOf('{', i);
    const semi = css.indexOf(';', i);
    if (open < 0) break;
    if (semi >= 0 && semi < open) { out.push({ text: css.slice(i, semi + 1).trim() }); i = semi + 1; continue; }
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}') { depth--; if (depth === 0) break; }
    }
    out.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j) });
    i = j + 1;
  }
  return out;
}

function splitSelectors(s) {
  const parts = [];
  let depth = 0;
  let cur = '';
  for (const ch of s) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { parts.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

function scopeSelector(sel, scope) {
  sel = sel.replace(/\s+/g, ' ').trim();
  // html / body / :root -> scope root
  const m = /^(html|body|:root)((?:[.#:\[][^ ]*)?)(.*)$/.exec(sel);
  if (m) {
    const [, , extra, rest] = m;
    if (m[1] === 'html' && /^ body/.test(rest)) return `${scope}${extra}${rest.replace(/^ body/, '')}`.trim();
    return `${scope}${extra}${rest}`.trim();
  }
  if (sel === '*' || sel.startsWith('*')) return `${scope} ${sel}`;
  if (sel.startsWith('::')) return `${scope} ${sel}`;
  return `${scope} ${sel}`;
}

function stateTwins(sel) {
  const twins = [sel];
  const map = [[/:hover/g, '.fx-hover'], [/:active/g, '.fx-active'], [/:focus-visible/g, '.fx-focus']];
  for (const [re, cls] of map) {
    if (re.test(sel)) twins.push(sel.replace(re, cls));
  }
  return twins;
}

function scopeCss(css, scope, tag) {
  const names = new Set();
  for (const m of css.matchAll(/@keyframes\s+([\w-]+)/g)) names.add(m[1]);
  const rename = (body) => {
    let b = body;
    for (const n of names) b = b.replace(new RegExp(`(animation(?:-name)?\\s*:[^;]*?)(?<![\\w-])${n}(?![\\w-])`, 'g'), `$1${tag}-${n}`);
    return b;
  };
  const emit = (list) => list.map((b) => {
    if (b.text) return b.text;
    if (/^@keyframes/.test(b.prelude)) {
      const name = b.prelude.replace(/^@keyframes\s+/, '');
      return `@keyframes ${tag}-${name} {${b.body}}`;
    }
    if (/^@media/.test(b.prelude)) return `${b.prelude} {\n${emit(blocks(b.body))}\n}`;
    if (/^@/.test(b.prelude)) return `${b.prelude} {${b.body}}`;
    const sels = splitSelectors(b.prelude).flatMap(stateTwins).map((s) => scopeSelector(s, scope));
    return `${sels.join(',\n')} {${rename(b.body)}}`;
  }).join('\n\n');
  return emit(blocks(css));
}

function tokensWithTwins(css) {
  // tokens.css stays global (variables, resets, buttons, mascot); only add the state twins.
  return blocks(css).map((b) => {
    if (b.text) return b.text;
    if (/^@media/.test(b.prelude)) return `${b.prelude} {\n${tokensWithTwins(b.body)}\n}`;
    if (/^@/.test(b.prelude)) return `${b.prelude} {${b.body}}`;
    return `${splitSelectors(b.prelude).flatMap(stateTwins).join(',\n')} {${b.body}}`;
  }).join('\n\n');
}

fs.mkdirSync(OUT, { recursive: true });
const banner = (src) => `/* Generated by video/tools/scope-css.mjs from src/renderer/${src} — do not edit. */\n`;
const read = (p) => fs.readFileSync(path.join(FLOCK, p), 'utf8');

fs.writeFileSync(path.join(OUT, 'tokens.css'), banner('shared/tokens.css') + tokensWithTwins(read('shared/tokens.css')));
fs.writeFileSync(path.join(OUT, 'island.css'), banner('island/island.css') + scopeCss(read('island/island.css'), '.fx-island', 'isl'));
fs.writeFileSync(path.join(OUT, 'settings.css'), banner('settings/settings.css') + scopeCss(read('settings/settings.css'), '.fx-settings', 'set'));
fs.writeFileSync(path.join(OUT, 'edge.css'), banner('edge/edge.css') + scopeCss(read('edge/edge.css'), '.fx-edge', 'edg'));
console.log('scoped CSS written to', OUT);
